/** Латинские буквы, которые выглядят как кириллические, не дублируем. */
const ALIASES = {
  A: 'А', B: 'В', C: 'С', E: 'Е', H: 'Н', K: 'К', M: 'М', O: 'О', P: 'Р', T: 'Т', X: 'Х', Y: 'У',
  Ё: 'Е', '×': 'Х', '•': '·', '–': '-', '—': '-',
};

/** Пиксельная карта символа или «?», если такого в шрифте нет. */
function shapeOf(char) {
  return SHAPES[char] ?? SHAPES[ALIASES[char]] ?? SHAPES['?'];
}

/** Левая и правая занятые колонки глифа — по ним считается ширина и пробелы. */
function bounds(rows) {
  let left = rows[0].length;
  let right = -1;
  for (const row of rows) {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] === '#') {
        left = Math.min(left, x);
        right = Math.max(right, x);
      }
    }
  }
  return { left, width: right - left + 1 };
}

/** Один раз рисуем каждый глиф нужным цветом в одиночный пиксельный холст. */
const glyphCache = new Map();

function glyphImage(char, color) {
  const key = `${color}|${char}`;
  let glyph = glyphCache.get(key);
  if (glyph) return glyph;

  const rows = shapeOf(char);
  const { left, width } = bounds(rows);
  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = GLYPH_HEIGHT;
  const g = canvas.getContext('2d');
  g.fillStyle = color;
  rows.forEach((row, y) => {
    for (let x = 0; x < width; x += 1) {
      if (row[left + x] === '#') g.fillRect(x, y, 1, 1);
    }
  });
  glyph = { canvas, width };
  glyphCache.set(key, glyph);
  return glyph;
}

function normalize(text) {
  return String(text).toUpperCase();
}

function advanceOf(char) {
  return char === ' ' ? SPACE_WIDTH : bounds(shapeOf(char)).width;
}

/** Ширина строки в экранных пикселях при данном масштабе. */
export function measureText(text, scale = 2) {
  const chars = [...normalize(text)];
  if (chars.length === 0) return 0;
  const units = chars.reduce((sum, char) => sum + advanceOf(char), 0) + SPACING * (chars.length - 1);
  return units * scale;
}

/** Высота строки текста в экранных пикселях. */
export function textHeight(scale = 2) {
  return GLYPH_HEIGHT * scale;
}

/**
 * Рисует текст пиксельным шрифтом. Верхний левый угол — (x, y).
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x
 * @param {number} y
 * @param {{color?: string, scale?: number, align?: 'left'|'center'|'right', shadow?: string|null}} [options]
 */
export function drawText(ctx, text, x, y, options = {}) {
  const { color = '#f0f3f9', scale = 2, align = 'left', shadow = '#05060c' } = options;
  const width = measureText(text, scale);
  let cursor = Math.round(align === 'center' ? x - width / 2 : align === 'right' ? x - width : x);
  const top = Math.round(y);
  const chars = [...normalize(text)];

  ctx.save();
  ctx.imageSmoothingEnabled = false;
  for (const char of chars) {
    if (char !== ' ') {
      if (shadow) {
        const dark = glyphImage(char, shadow);
        ctx.drawImage(dark.canvas, cursor + scale, top + scale, dark.width * scale, GLYPH_HEIGHT * scale);
      }
      const glyph = glyphImage(char, color);
      ctx.drawImage(glyph.canvas, cursor, top, glyph.width * scale, GLYPH_HEIGHT * scale);
    }
    cursor += (advanceOf(char) + SPACING) * scale;
  }
  ctx.restore();
}

/** Режет текст на строки не шире maxWidth (по словам). */
export function wrapText(text, maxWidth, scale = 2) {
  const lines = [];
  let line = '';
  for (const word of String(text).split(' ')) {
    const candidate = line ? `${line} ${word}` : word;
    if (line && measureText(candidate, scale) > maxWidth) {
      lines.push(line);
      line = word;
    } else {
      line = candidate;
    }
  }
  if (line) lines.push(line);
  return lines;
}
