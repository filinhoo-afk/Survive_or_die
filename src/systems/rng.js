/**
 * Случайные числа забега.
 *
 * Обычный забег играет на `Math.random`. В испытании дня у всех игроков один
 * сид, и всё, что решает судьба мира, берётся из генератора с этим сидом:
 * расстановка ящиков, кто и откуда выходит в волнах, какие бывают элиты,
 * куда бьют боссы, какие карточки предлагают. Мир получается одинаковым у всех,
 * а исход — разным: он зависит от того, как играет человек.
 *
 * Потоков два. Волны (`spawn`) зависят только от времени забега, поэтому у
 * всех выходят одни и те же враги в одних и тех же местах. Остальное (`world`)
 * дёргается от действий игрока: что он разбил, какую карточку получил.
 * Раздельные потоки не дают одному сбить другой.
 *
 * Косметика — частицы, тряска, звук — остаётся на `Math.random`: у неё нет
 * веса для игры, и тратить на неё числа сида незачем.
 */

/** Генератор mulberry32: из 32-битного сида — числа в [0, 1). Мал, быстр, воспроизводим. */
export function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Что делать с потоком, пока сида нет: обычная случайность. */
const unseeded = () => Math.random();

const streams = { spawn: unseeded, world: unseeded };

/** Второй поток растёт из того же сида, но не повторяет первый. */
const WORLD_SALT = 0x9e3779b9;

/** Включает общий сид: оба потока начинают с начала. */
export function seedRun(seed) {
  streams.spawn = mulberry32(seed);
  streams.world = mulberry32((seed ^ WORLD_SALT) >>> 0);
}

/** Возвращает обычную случайность — для всех забегов, кроме испытания дня. */
export function unseedRun() {
  streams.spawn = unseeded;
  streams.world = unseeded;
}

/** Число в [0, 1) из потока: 'spawn' — волны, 'world' — всё остальное. */
export function random(stream = 'world') {
  return streams[stream]();
}

/** Подпись сида для экрана: восемь шестнадцатеричных цифр. */
export function seedLabel(seed) {
  return (seed >>> 0).toString(16).toUpperCase().padStart(8, '0');
}
