/**
 * Заглушка canvas для тестов в Node.
 *
 * Атлас спрайтов (src/gfx/atlas.js) рисует все кадры в canvas прямо при
 * загрузке модуля, а до него дотягиваются враги, игрок, оружие и препятствия.
 * Пиксельные карты при этом разбираются по-настоящему — подделан только сам
 * холст, поэтому битая карта спрайта роняет тест, как роняет игру.
 *
 * Файл подключают первой строкой теста, до любых модулей игры:
 *   import '../helpers/dom.js';
 */

const ctx = new Proxy(
  {},
  {
    get: () => () => {},
    set: () => true,
  },
);

if (typeof globalThis.document === 'undefined') {
  globalThis.document = {
    createElement: () => ({ width: 0, height: 0, getContext: () => ctx }),
  };
}
